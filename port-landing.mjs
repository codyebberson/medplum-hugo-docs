// Exports the Docusaurus /products page (React) to static Hugo partials and CSS.
//
// The products page components in the medplum repo are the source of truth until the Hugo site
// replaces Docusaurus. Rather than hand-port ~2,000 lines of illustration JSX, this script renders
// the page once with React's server renderer, converts the CSS modules to plain CSS with stable
// class names, and writes the results into this repo. Re-run it whenever the React version changes.
//
// The interactive behavior (auto-advancing tabs, carousel, diagram connectors, slideshow) is
// hand-written in assets/js/components/products/ and binds to the generated class names.
//
// Usage: node port-landing.mjs   (expects the medplum repo at ../medplum, or set MEDPLUM_REPO)

import fs from 'node:fs';
import os from 'node:os';
import path, { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import postcss from 'postcss';

const medplumRoot = resolve(process.env.MEDPLUM_REPO ?? '../medplum');
const docsRoot = path.join(medplumRoot, 'packages/docs');
const srcRoot = path.join(docsRoot, 'src');

const outPartial = resolve('./layouts/partials/products/generated/page.html');
const outCss = resolve('./assets/css/generated/products.css');

const GENERATED_HEADER = 'GENERATED by port-landing.mjs from the medplum repo. Do not edit by hand; re-run the script.';

// Class names the hand-written JS in assets/js/components/products/ depends on.
// The script fails if a React refactor renames any of them.
const REQUIRED_CLASSES = [
  'products-apps-tab',
  'products-apps-tab-active',
  'products-apps-tab-progress',
  'products-apps-tab-progress-full',
  'products-apps-app-description',
  'products-apps-image-stack',
  'products-apps-stack-card',
  'products-apps-stack-front',
  'products-apps-stack-back',
  'products-apps-anim-to-front',
  'products-apps-anim-to-back',
  'products-foundations-carousel-item',
  'products-foundations-carousel-item-active',
  'products-foundations-carousel-item-progress',
  'products-foundations-carousel-item-progress-full',
  'products-foundations-carousel-item-body-wrap',
  'products-foundations-carousel-item-body-wrap-open',
  'products-foundations-carousel-item-body-inner',
  'products-foundations-carousel-image-area',
  'products-foundations-carousel-media-swap',
  'products-foundations-carousel-media-swap-exiting',
  'products-cta-browser-image',
  'products-cta-slide',
  'products-cta-slide-active',
];

async function main() {
  const esbuild = await importFromMedplum('esbuild');
  const prettier = await importFromMedplum('prettier');

  const cssModules = new Map(); // file path -> { prefix, classMap, css }

  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'port-landing-'));
  const bundlePath = path.join(tmpDir, 'render.mjs');

  await esbuild.build({
    stdin: { contents: ENTRY, resolveDir: srcRoot, loader: 'tsx', sourcefile: 'port-landing-entry.tsx' },
    bundle: true,
    platform: 'node',
    format: 'esm',
    outfile: bundlePath,
    jsx: 'automatic',
    logLevel: 'warning',
    // react-dom/server is CommonJS and requires Node built-ins, which an ESM bundle can't do without this
    banner: { js: `import { createRequire } from 'node:module'; const require = createRequire(import.meta.url);` },
    define: { 'process.env.NODE_ENV': '"production"' },
    nodePaths: [path.join(medplumRoot, 'node_modules')],
    plugins: [mocksPlugin(), sourceTransformsPlugin(), cssModulesPlugin(cssModules)],
  });

  const { render } = await import(pathToFileURL(bundlePath).href);
  const result = render();
  fs.rmSync(tmpDir, { recursive: true, force: true });

  // CSS: shared landing tokens (global, unrenamed) followed by every CSS module the page imported
  const tokens = fs.readFileSync(path.join(srcRoot, 'css/landing-tokens.css'), 'utf8');
  const allClasses = new Set();
  const cssParts = [`/* ${GENERATED_HEADER} */`, '', '/* ---- src/css/landing-tokens.css ---- */', tokens];
  for (const [file, mod] of cssModules) {
    cssParts.push(`/* ---- ${path.relative(docsRoot, file)} ---- */`, mod.css);
    Object.values(mod.classMap).forEach((v) => v.split(' ').forEach((c) => allClasses.add(c)));
  }
  const missing = REQUIRED_CLASSES.filter((c) => !allClasses.has(c));
  if (missing.length > 0) {
    throw new Error('Classes required by assets/js/components/products/ no longer exist:\n  ' + missing.join('\n  '));
  }

  // HTML: page markup, then the foundation media the carousel swaps in, then app data for the tabs
  let html = result.page;
  html += '\n<div hidden>\n';
  result.media.forEach((media, i) => {
    html += `<template class="products-foundation-media" data-index="${i}">${media}</template>\n`;
  });
  html += '</div>\n';
  html += `<script type="application/json" class="products-apps-data">${JSON.stringify(result.apps)}</script>\n`;

  if (html.includes('{{')) {
    throw new Error('Rendered markup contains "{{", which Hugo would parse as a template action');
  }
  // Format before replacing placeholders: Prettier leaves attribute values alone, but would wrap the JSON in a partial call
  const formatted = replacePartialPlaceholders(await prettier.format(html, { parser: 'html', printWidth: 160 }));

  fs.mkdirSync(path.dirname(outPartial), { recursive: true });
  fs.writeFileSync(outPartial, `{{- /* ${GENERATED_HEADER} */ -}}\n` + formatted, 'utf8');
  console.log(`Wrote ${path.relative('.', outPartial)}`);

  fs.mkdirSync(path.dirname(outCss), { recursive: true });
  fs.writeFileSync(outCss, cssParts.join('\n') + '\n', 'utf8');
  console.log(`Wrote ${path.relative('.', outCss)} (${cssModules.size} CSS modules)`);

  copyImages(formatted + cssParts.join('\n'));
}

// The virtual entry point, compiled with the medplum repo's dependencies.
const ENTRY = `
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import ProductsPage from './pages/products/index';
import { FOUNDATION_MEDIA } from './components/landing/ProductsFoundationsCarousel';
import { FEATURED_APPS, FOUNDATIONS } from './data/products-content';

export function render() {
  return {
    page: renderToStaticMarkup(createElement(ProductsPage)),
    media: FOUNDATIONS.map((f) => (FOUNDATION_MEDIA[f.name] ? renderToStaticMarkup(FOUNDATION_MEDIA[f.name]) : '')),
    apps: FEATURED_APPS.map(({ id, body }) => ({ id, body })),
  };
}
`;

// Placeholder element for components that already exist as Hugo partials.
// Rendered as <hugo-partial>, then rewritten to a {{ partial }} call (see replacePartialPlaceholders).
const PLACEHOLDER = `
import { createElement } from 'react';
export function hugoPartial(name, args) {
  return createElement('hugo-partial', { name, args: JSON.stringify(args) });
}
`;

function mocksPlugin() {
  const mocks = {
    '@docusaurus/Link': `
      import { createElement } from 'react';
      export default function Link({ to, href, ...rest }) { return createElement('a', { href: to ?? href, ...rest }); }`,
    '@theme/Layout': `
      import { createElement, Fragment } from 'react';
      export default function Layout({ children }) { return createElement(Fragment, null, children); }`,
    // Navbar scroll behavior lives in assets/js/main.mjs
    '../../hooks/useNavbarScroll': `export function useNavbarScroll() {}`,
    // Rendered by layouts/partials/landing/build-dropdown.html
    './BuildDropdown': `
      import { hugoPartial } from 'hugo-placeholder';
      export function BuildDropdown({ label, triggerClassName } = {}) {
        return hugoPartial('landing/build-dropdown', { label, triggerClass: triggerClassName });
      }`,
    'hugo-placeholder': PLACEHOLDER,
  };

  return {
    name: 'mocks',
    setup(build) {
      build.onResolve({ filter: /.*/ }, (args) => (args.path in mocks ? { path: args.path, namespace: 'mock' } : undefined));
      build.onLoad({ filter: /.*/, namespace: 'mock' }, (args) => ({ contents: mocks[args.path], loader: 'jsx', resolveDir: srcRoot }));
    },
  };
}

// Small, asserted edits to the React source so the static output carries the hooks the JS needs.
function sourceTransformsPlugin() {
  const transforms = {
    'ProductsDiagram.tsx': (src) => {
      // Tag every measured node so assets/js/components/products/diagram.mjs can find it
      src = replaceRequired(src, /ref=\{rootRef\}/, 'ref={rootRef} data-dg-root=""');
      src = replaceRequired(src, /\bref=\{refs\.(\w+)\}/g, 'ref={refs.$1} data-dg="$1"');
      src = replaceRequired(src, /\bnodeRef=\{refs\.(\w+)\}/g, 'nodeRef={refs.$1} data-dg="$1"');
      return src;
    },
    'ProductsFoundationsCarousel.tsx': (src) => {
      // Expose the per-foundation media so every slide can be rendered, not just the first
      if (!src.includes('const FOUNDATION_MEDIA')) {
        throw new Error('ProductsFoundationsCarousel.tsx: FOUNDATION_MEDIA not found');
      }
      return src + '\nexport { FOUNDATION_MEDIA };\n';
    },
    'CapabilityPreviews.tsx': (src) => {
      // Mark the Messaging preview, whose chat bubbles are sized from measured text widths
      const start = src.indexOf('function MessagingPreview(');
      const svg = src.indexOf('<svg', start);
      if (start < 0 || svg < 0) {
        throw new Error('CapabilityPreviews.tsx: MessagingPreview <svg> not found');
      }
      return src.slice(0, svg) + '<svg data-measure-bubbles=""' + src.slice(svg + 4);
    },
    'ComplianceBadges.tsx': (src) => {
      // Keep the real badge data; render the component through layouts/partials/landing/compliance-badges.html
      src = replaceRequired(src, /export function ComplianceBadges\(/, 'function OriginalComplianceBadges(');
      return (
        `import { hugoPartial } from 'hugo-placeholder';\n` +
        src +
        `\nexport function ComplianceBadges({ badges = COMPLIANCE_BADGES, variant } = {}) {
          return hugoPartial('landing/compliance-badges', { badges, variant });
        }\n`
      );
    },
  };

  return {
    name: 'source-transforms',
    setup(build) {
      build.onLoad({ filter: /components\/landing\/\w+\.tsx$/ }, (args) => {
        const transform = transforms[path.basename(args.path)];
        if (!transform) {
          return undefined;
        }
        return { contents: transform(fs.readFileSync(args.path, 'utf8')), loader: 'tsx', resolveDir: path.dirname(args.path) };
      });
    },
  };
}

function replaceRequired(src, pattern, replacement) {
  if (!pattern.test(src)) {
    throw new Error(`Source transform pattern not found: ${pattern}`);
  }
  pattern.lastIndex = 0;
  return src.replace(pattern, replacement);
}

// Converts CSS modules to global CSS with stable, readable class names:
//   ProductsApps.module.css .tabProgress  ->  .products-apps-tab-progress
// Local @keyframes are renamed the same way. `composes:` becomes extra class names in the markup,
// which is what CSS modules do at runtime.
function cssModulesPlugin(cssModules) {
  return {
    name: 'css-modules',
    setup(build) {
      build.onLoad({ filter: /\.module\.css$/ }, (args) => {
        const mod = convertCssModule(args.path);
        cssModules.set(args.path, mod);
        return { contents: `export default ${JSON.stringify(mod.classMap)};`, loader: 'js' };
      });
    },
  };
}

function convertCssModule(file) {
  const base = path.basename(file, '.module.css');
  const prefix = base === 'products' ? 'products-page' : kebab(base);
  const rename = (name) => `${prefix}-${kebab(name)}`;

  const root = postcss.parse(fs.readFileSync(file, 'utf8'), { from: file });
  const keyframes = new Set();
  root.walkAtRules(/keyframes$/, (rule) => keyframes.add(rule.params.trim()));

  const classMap = {};
  const composes = {};

  root.walkRules((rule) => {
    if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) {
      return;
    }
    rule.selector = rule.selector.replace(/\.(-?[_a-zA-Z][\w-]*)/g, (_, name) => {
      classMap[name] = rename(name);
      return '.' + rename(name);
    });
    rule.walkDecls('composes', (decl) => {
      const owner = rule.selector.match(/^\.([\w-]+)$/);
      if (!owner) {
        throw new Error(`${file}: composes is only supported on single-class rules (${rule.selector})`);
      }
      composes[owner[1]] = decl.value.split(/\s+/);
      decl.remove();
    });
  });

  root.walkAtRules(/keyframes$/, (rule) => {
    rule.params = rename(rule.params.trim());
  });
  root.walkDecls(/^animation(-name)?$/, (decl) => {
    decl.value = decl.value.replace(/[\w-]+/g, (token) => (keyframes.has(token) ? rename(token) : token));
  });

  // Resolve composes into the class map (by original name)
  for (const [name, renamed] of Object.entries(classMap)) {
    const extra = Object.entries(composes)
      .filter(([owner]) => owner === renamed)
      .flatMap(([, list]) => list.map(rename));
    if (extra.length > 0) {
      classMap[name] = [renamed, ...extra].join(' ');
    }
  }

  return { prefix, classMap, css: root.toString() };
}

function kebab(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase();
}

// <hugo-partial name="landing/x" args="{json}"></hugo-partial>  ->  {{ partial "landing/x" (transform.Unmarshal `{json}`) }}
function replacePartialPlaceholders(html) {
  // Prettier may switch the args attribute to single quotes and split the closing tag across lines
  const pattern = /<hugo-partial\s+name="([^"]+)"\s+args=(?:"([^"]*)"|'([^']*)')\s*><\/hugo-partial\s*>/g;
  const result = html.replace(pattern, (_, name, doubleQuoted, singleQuoted) => {
    const args = doubleQuoted ?? singleQuoted;
    const json = args.replace(/&quot;/g, '"').replace(/&#x27;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
    if (json.includes('`')) {
      throw new Error(`Partial args for ${name} contain a backtick: ${json}`);
    }
    return `{{ partial "${name}" (transform.Unmarshal \`${json}\`) }}`;
  });
  if (result.includes('hugo-partial')) {
    throw new Error('Unreplaced <hugo-partial> placeholder in output');
  }
  return result;
}

// Copies every /img/... referenced by the output from the medplum repo when missing or changed
function copyImages(text) {
  const images = new Set(text.match(/\/img\/[\w./-]+\.(?:svg|png|webp|jpg|jpeg|gif)/g) ?? []);
  let copied = 0;
  for (const img of images) {
    const src = path.join(docsRoot, 'static', img);
    const dest = resolve('./static' + img);
    if (!fs.existsSync(src)) {
      console.warn(`Image not found in medplum repo: ${img}`);
      continue;
    }
    if (!fs.existsSync(dest) || !fs.readFileSync(src).equals(fs.readFileSync(dest))) {
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.copyFileSync(src, dest);
      copied++;
      console.log(`Copied ${img}`);
    }
  }
  console.log(`Images: ${images.size} referenced, ${copied} copied`);
}

async function importFromMedplum(pkg) {
  const { createRequire } = await import('node:module');
  const require = createRequire(path.join(medplumRoot, 'package.json'));
  const mod = await import(pathToFileURL(require.resolve(pkg)).href);
  return mod.default ?? mod;
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
